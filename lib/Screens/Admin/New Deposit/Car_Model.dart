class Car {
  String model;
  String plateNumber;
  int year;
  String color;
  String driverName;
  String modelName;
  int carId;

  Car({
    required this.model,
    required this.plateNumber,
    required this.year,
    required this.color,
    required this.driverName,
    required this.modelName,
    required this.carId,
  });
}